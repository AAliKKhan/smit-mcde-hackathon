"""Profiling pass over raw.* - run BEFORE cleaning (case study hint:
"Profile before you clean"). Writes docs/profile_notes.md and prints a summary.

Evidence gathered here feeds SC-003 (planted-issue inventory) and answers the
OPEN points in specs/001-hr-pipeline/research.md.

Usage: python -m ingestion.profile
"""

from __future__ import annotations

import re
from datetime import datetime

import pandas as pd

from config import DOCS_DIR
from common import db

OUT = DOCS_DIR / "profile_notes.md"

ISO = re.compile(r"^\d{4}-\d{2}-\d{2}$")
SLASH = re.compile(r"^\d{2}/\d{2}/\d{4}$")
MON = re.compile(r"^\d{2}-[A-Za-z]{3}-\d{4}$")


def _date_formats(values) -> dict[str, int]:
    out = {"YYYY-MM-DD": 0, "DD/MM/YYYY": 0, "DD-Mon-YYYY": 0, "other/empty": 0}
    for v in values:
        v = (v or "").strip()
        if not v:
            out["other/empty"] += 1
        elif ISO.match(v):
            out["YYYY-MM-DD"] += 1
        elif SLASH.match(v):
            out["DD/MM/YYYY"] += 1
        elif MON.match(v):
            out["DD-Mon-YYYY"] += 1
        else:
            out["other/empty"] += 1
    return out


def main() -> int:
    md: list[str] = [
        "# Profile notes - raw exports (generated by ingestion/profile.py)",
        "",
        f"Generated: {datetime.now().isoformat(timespec='seconds')}",
        "",
        "Planted issues found here MUST be fixed in code (Principle V) and",
        "re-verified after Stage 2 (SC-003).",
    ]
    notes: list[str] = []

    def sec(title: str) -> None:
        print(f"\n== {title}")
        md.append(f"\n## {title}\n")

    q = db.read_sql

    # ------------------------------------------------------------ employees
    sec("employees.csv (1,316 rows)")
    emp = q("SELECT * FROM raw.employees")
    for col in ("hire_date", "separation_date", "date_of_birth"):
        fmt = _date_formats(emp[col])
        line = f"- `{col}` formats: {fmt}"
        md.append(line)
        notes.append(line)
        print(f"  {col}: {fmt}")
    dup = q(
        "SELECT COUNT(*) AS n FROM (SELECT emp_id FROM raw.employees "
        "GROUP BY emp_id HAVING COUNT(*) > 1)"
    )["n"][0]
    rows_over = q(
        "SELECT COUNT(*) AS n FROM raw.employees e WHERE e.emp_id IN "
        "(SELECT emp_id FROM raw.employees GROUP BY emp_id HAVING COUNT(*) > 1)"
    )["n"][0]
    line = f"- duplicate emp_ids: **{dup} ids covering {rows_over} rows** (keep latest updated_at, Rule 1)"
    md.append(line)
    notes.append(line)
    print(f"  duplicate emp_ids: {dup} ids / {rows_over} rows")
    messy = q(
        "SELECT COUNT(*) AS n FROM raw.employees WHERE department != TRIM(department)"
    )["n"][0]
    md.append(f"- department strings needing case/space normalization: **{messy} rows**")
    notes.append(f"messy department strings: {messy}")
    print(f"  messy department strings: {messy}")
    plants = q("SELECT plant, COUNT(*) AS n FROM raw.employees GROUP BY plant ORDER BY 2 DESC")
    md.append("- plants: " + ", ".join(f"{r.plant}={r.n}" for r in plants.itertuples()))
    print("  plants:", dict(zip(plants["plant"], plants["n"])))
    variants = q("SELECT TRIM(department) AS d, COUNT(*) AS n FROM raw.employees GROUP BY 1 ORDER BY 1")
    md.append(f"- distinct trimmed department strings: {len(variants)}")
    print(f"  distinct trimmed dept strings: {len(variants)}")

    # ---------------------------------------------------- employment history
    sec("employment_history.csv (3,686 rows)")
    hist = q(
        """
        SELECT emp_id, effective_from, effective_to,
               LEAD(effective_from) OVER (PARTITION BY emp_id ORDER BY effective_from) AS next_from
        FROM raw.employment_history
        """
    )
    open_ = hist[(hist["effective_to"].str.strip() != "") & hist["effective_to"].notna()]
    nxt = open_[open_["next_from"].notna()].copy()
    nxt["d_to"] = pd.to_datetime(nxt["effective_to"], errors="coerce")
    nxt["d_nx"] = pd.to_datetime(nxt["next_from"], errors="coerce")
    overlaps = nxt[nxt["d_to"] >= nxt["d_nx"]]
    gaps = nxt[nxt["d_to"] < nxt["d_nx"] - pd.Timedelta(days=1)]
    line = (
        f"- unreliable effective_to: **{len(overlaps)} overlap rows / {len(gaps)} gap rows** "
        f"across {len(set(overlaps['emp_id']) | set(gaps['emp_id']))} employees "
        f"(case study says 37 - Rule 2 recompute required)"
    )
    md.append(line)
    notes.append(line)
    print(f"  overlaps={len(overlaps)} gaps={len(gaps)} emps={len(set(overlaps['emp_id']) | set(gaps['emp_id']))}")

    # --------------------------------------------------------------- shifts
    sec("shifts.json / shift_roster.csv")
    shifts = q("SELECT * FROM raw.shifts")
    md.append("- shifts: " + "; ".join(
        f"{r.shift_code} {r.start_time}-{r.end_time}"
        + (" (crosses midnight)" if str(r.crosses_midnight).lower() == "true" else "")
        for r in shifts.itertuples()
    ))
    print(f"  shifts: {len(shifts)}")
    minmax = q(
        "SELECT MIN(week_start) AS w0, MAX(week_start) AS w1, "
        "COUNT(DISTINCT week_start) AS nw, COUNT(DISTINCT emp_id) AS ne "
        "FROM raw.shift_roster"
    )
    md.append(f"- roster: {minmax['w0'][0]} .. {minmax['w1'][0]}, "
              f"{minmax['nw'][0]} distinct weeks, {minmax['ne'][0]} employees")
    print("  roster:", minmax.iloc[0].to_dict())
    no_ros = q(
        "SELECT COUNT(*) AS n FROM raw.employees e "
        "WHERE NOT EXISTS (SELECT 1 FROM raw.shift_roster r WHERE r.emp_id = e.emp_id)"
    )["n"][0]
    line = f"- employees with NO roster rows at all: **{no_ros}** (Rule-5 default shift needed)"
    md.append(line)
    notes.append(line)
    print(f"  employees without roster rows: {no_ros}")
    # how many (emp, week) pairs missing inside each employee's own span
    ros = q("SELECT emp_id, week_start FROM raw.shift_roster ORDER BY emp_id, week_start")
    ros["ws"] = pd.to_datetime(ros["week_start"])
    g_emps, g_missing = 0, 0
    for _, g in ros.groupby("emp_id"):
        weeks = (g["ws"].max() - g["ws"].min()).days // 7 + 1
        have = len(g["ws"].unique())
        if weeks > have:
            g_emps += 1
            g_missing += weeks - have
    line = f"- roster gaps inside employee span: **{g_emps} employees, {g_missing} missing weeks** (Rule 6 forward-fill)"
    md.append(line)
    notes.append(line)
    print(f"  roster gaps: {g_emps} emps / {g_missing} weeks")

    # -------------------------------------------------------------- punches
    sec("biometric_punches.csv (345,280 rows)")
    unmapped = q(
        "SELECT COUNT(*) AS n FROM raw.biometric_punches p WHERE NOT EXISTS ("
        " SELECT 1 FROM raw.device_mapping m WHERE m.device_id = p.device_id"
        " AND m.device_user_id = p.device_user_id)"
    )["n"][0]
    line = f"- punches without composite mapping (Rule 8 -> rejected): **{unmapped}**"
    md.append(line)
    notes.append(line)
    print(f"  unmapped punches: {unmapped}")
    devices = q(
        """
        SELECT p.device_id, COUNT(*) AS punches,
               ROUND(AVG(CAST(strftime('%H', p.punch_time) AS INT) * 60
                       + CAST(strftime('%M', p.punch_time) AS INT)) / 60.0, 2) AS avg_hour
        FROM raw.biometric_punches p GROUP BY p.device_id ORDER BY avg_hour
        """
    )
    md.append("- avg clock-time of punches per device (drift signal, Rule 11):")
    for r in devices.itertuples():
        md.append(f"  - `{r.device_id}`: avg **{r.avg_hour} h** over {r.punches:,} punches")
        print(f"  {r.device_id}: avg={r.avg_hour} n={r.punches}")
    dup2min = q(
        """
        WITH s AS (
          SELECT p.device_id AS did, p.device_user_id AS uid, p.punch_time,
                 LAG(p.punch_time) OVER (PARTITION BY p.device_id, p.device_user_id
                                         ORDER BY p.punch_time) AS prev
          FROM raw.biometric_punches p
        )
        SELECT COUNT(*) AS n FROM s
        WHERE prev IS NOT NULL AND (julianday(punch_time) - julianday(prev)) * 1440.0 < 2.0
        """
    )["n"][0]
    line = f"- punch pairs < 2 minutes apart (Rule 9 collapse candidates): **{dup2min}**"
    md.append(line)
    notes.append(line)
    print(f"  <2min pairs: {dup2min}")
    pr = q("SELECT MIN(punch_time) AS a, MAX(punch_time) AS b FROM raw.biometric_punches")
    md.append(f"- punch range: {pr['a'][0]} .. {pr['b'][0]} (1-Oct spillover = Rule 7 evidence)")
    print("  range:", pr.iloc[0].to_dict())

    # ---------------------------------------------------------------- leave
    sec("leave_requests.json (5,372 requests)")
    lt = q(
        "SELECT json_extract(`leave`, '$.type') AS t, COUNT(*) AS n "
        "FROM raw.leave_requests GROUP BY 1 ORDER BY 2 DESC"
    )
    line = "- leave types: " + ", ".join(f"{r.t}={r.n}" for r in lt.itertuples())
    md.append(line)
    notes.append(f"leave types: {dict(zip(lt['t'], lt['n']))}")
    print("  types:", dict(zip(lt["t"], lt["n"])))
    acts = q(
        "SELECT json_extract(j.value, '$.action') AS action, COUNT(*) AS n "
        "FROM raw.leave_requests r, json_each(r.approvals) j GROUP BY 1 ORDER BY 2 DESC"
    )
    md.append("- approval step actions: " + ", ".join(f"{r.action}={r.n}" for r in acts.itertuples()))
    print("  actions:", dict(zip(acts["action"], acts["n"])))
    canc = q(
        "SELECT SUM(CASE WHEN cancelled_at IS NOT NULL AND cancelled_at != '' "
        "THEN 1 ELSE 0 END) AS n FROM raw.leave_requests"
    )["n"][0]
    steps = q(
        "SELECT MIN(c) AS mn, MAX(c) AS mx, SUM(CASE WHEN c != 2 THEN 1 ELSE 0 END) AS not2 "
        "FROM (SELECT r.request_id, COUNT(j.value) AS c FROM raw.leave_requests r "
        "LEFT JOIN json_each(r.approvals) j GROUP BY r.request_id)"
    )
    both = q(
        """
        SELECT SUM(CASE WHEN n_appr = 2 AND (cancelled_at IS NULL OR cancelled_at = '')
                        THEN 1 ELSE 0 END) AS countable,
               COUNT(*) AS total
        FROM (
          SELECT r.request_id, r.cancelled_at,
                 SUM(CASE WHEN json_extract(j.value, '$.action') = 'Approved'
                          THEN 1 ELSE 0 END) AS n_appr
          FROM raw.leave_requests r, json_each(r.approvals) j
          GROUP BY r.request_id
        )
        """
    )
    line = (f"- cancelled={canc}, steps/request {steps['mn'][0]}-{steps['mx'][0]} "
            f"(not exactly 2: {steps['not2'][0]}); fully-approved & not-cancelled: "
            f"**{both['countable'][0]} / {both['total'][0]}** (Rule 16)")
    md.append(line)
    notes.append(line)
    print("  rule16 countable:", both.iloc[0].to_dict())

    # ------------------------------------------------------------------- OT
    sec("overtime_requests.csv (22,098 rows)")
    st = q("SELECT status, COUNT(*) AS n FROM raw.overtime_requests GROUP BY 1 ORDER BY 2 DESC")
    md.append("- OT statuses: " + ", ".join(f"{r.status}={r.n}" for r in st.itertuples()))
    print("  statuses:", dict(zip(st["status"], st["n"])))

    # -------------------------------------------------------------- payroll
    sec("payroll_lines.csv (53,617 rows)")
    comp = q(
        "SELECT component, component_type, COUNT(*) AS n, "
        "SUM(CASE WHEN units IS NOT NULL AND units != '' THEN 1 ELSE 0 END) AS with_units "
        "FROM raw.payroll_lines GROUP BY 1, 2 ORDER BY 1"
    )
    md.append("- components:")
    for r in comp.itertuples():
        md.append(f"  - {r.component} ({r.component_type}): {r.n} rows, {r.with_units} with units")
    print("  components:", comp[["component", "component_type", "n"]].to_dict("records"))
    months = q("SELECT DISTINCT payroll_month FROM raw.payroll_lines ORDER BY 1")
    md.append(f"- payroll months: {list(months['payroll_month'])}")
    print("  months:", list(months["payroll_month"]))

    # -------------------------------------------------------------- holidays
    sec("holidays.csv (12 rows)")
    hol = q("SELECT scope, COUNT(*) AS n FROM raw.holidays GROUP BY 1 ORDER BY 1")
    md.append("- scopes: " + ", ".join(f"{r.scope}={r.n}" for r in hol.itertuples()))
    print("  scopes:", dict(zip(hol["scope"], hol["n"])))

    # ---------------------------------------------------------- departments
    sec("departments.csv (25 rows)")
    ren = q(
        "SELECT dept_id, dept_name, previous_name, renamed_on FROM raw.departments "
        "WHERE previous_name IS NOT NULL AND previous_name != ''"
    )
    for r in ren.itertuples():
        md.append(f"- renamed: **{r.dept_id}** {r.previous_name} -> {r.dept_name} on {r.renamed_on}")
        print(f"  rename: {r.dept_id} {r.previous_name} -> {r.dept_name}")

    # --------------------------------------------------------------- summary
    md.append("\n## Planted-issue inventory (for SC-003 evidence)\n")
    for i, n in enumerate(notes, 1):
        md.append(f"{i}. {n}")
    md.append(
        "\nSee transform/* for the code that fixes each item; "
        "tests/test_staging_invariants.py re-verifies them (Gate S)."
    )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"\nwritten: {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
